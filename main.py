import os
import dotenv

from langchain_google_genai import GoogleGenerativeAI
from langchain_core.prompts import PromptTemplate

dotenv.load_dotenv()
API_KEY = os.getenv("GEMINI_API_KEY")

llm = GoogleGenerativeAI(
    model='gemma-3-1b-it',
    api_key=API_KEY,
    temperature=0
)

prompt = PromptTemplate.from_template("""Ти – голова навчального відділу навчального закладу.
Твоє завдання - створення плану курсу в залежності від аудиторії і теми.

### ІНСТРУКЦІЇ
0. На сам початок напиши в залежності від запиту користувача "моя цільова аудиторія - ..., а тема курсу - ...", і вже відповідно до цього дій
1. Створи курс так, щоб він був сучасним
2. Створюй курс так, щоб він не був переповнений теорією, а був з акцентом на практику
3. Створюй курс так, щоб він був з розрахунком на академічний рік (тривалість – ОБОВ'ЯЗКОВО 9 місяців)
4. Розбий курс на теми та підтеми, щоб була чітка структура (КІЛЬКІСТЬ ТИМ НЕ ОБОВ'ЯЗКОВО СПІВАТИСЯ З КІЛЬКОСТЮ МІСЯЦІВ)

Також вкажи конкретно, на кого розрахований курс і яку основу необхідно мати.
Чи потрібні додаткові ресурси для проходження курсу (обладнання, підписки тощо), НАПИШИ ПРО РЕСУРСИ ЛИШЕ НА САМОМУ ПОЧАТКУ.

ДУЖЕ ВАЖЛИВО
Якщо користувач не вказав коректно або цільову аудиторію (наприклад, діти, початківці, професіонали тощо),
або тему (наприклад, програмування, іноземна мова, математика тощо), дай відповідь, що запит не повний. ЯКЩО НАПИСАВ МАЯЧНЮ, ТО ПРОСТО ПРОІГНОРУЙ.

### ДИСКЛЕЙМЕР (ДУЖЕ ВАЖЛИВО)
Насамкінець додай що план не є оптимальним, а що його можна брати як основу,
і що його потрібно підлаштовувати індивідуально під потреби групу.

### ПРИКЛАД
Добре, давайте розробимо план курсу з економіки для дітей, з урахуванням сучасного підходу та акцентом на практиці.

**1.  Представлення цільової аудиторії та теми:**

*   **Цільова аудиторія:** Діти 6-12 років.
*   **Тема:**  Економіка.

**2.  Мета курсу:**

Після проходження курсу діти зможуть:

*   Розуміти основні економічні поняття (наприклад, доходи, витрати, збагачення, економічні кризи).
*   Аналізувати економічні ситуації та робити прості прогнози.
*   Визначати потреби та можливості в реальному житті, використовуючи економічні принципи.
*   Розуміти вплив економічних факторів на суспільство.

**3.  Структура курсу (9 місяців):**

Курс розбивається на 9 місяців, з акцентом на практичні завдання та ігрові елементи.

*   **Місяць 1:  Вступ до економіки – Що це таке?**
    *   Тема:  Що таке економіка?  Як економіка впливає на наше життя.
    *   Творчі завдання:  Створення "економічного плану" для свого будинку (визначення потреб, виділення бюджету).
    *   Ресурси:  Відео про економіку для дітей, інтерактивні ігри про витрати та доходи.
*   **Місяць 2:  Доходи та витрати –  Як ми отримуємо гроші?**
    *   Тема:  Типи доходів (зарплата, подарунки, доходи від майна).  Витрати (їжа, одяг, розваги).
    *   Творчі завдання:  Створення "економічного балансу" для сім'ї (визначення, що виходить з кожного доходу, що витрачається).
    *   Ресурси:  Інтерактивні ігри про витрати та доходи, приклади з реального життя.
*   **Місяць 3:  Збагачення та економічні кризи –  Що таке збагачення?**
    *   Тема:  Що таке збагачення?  Як збагачуються люди?  Економічні кризи – що це таке?
    *   Творчі завдання:  Створення "економічного сценарію" (як би ви могли збагатити себе?).
    *   Ресурси:  Інтерактивні ігри про збагачення, приклади з історії економічних криз.
*   **Місяць 4:  Економіка в сім'ї –  Як працює сім'я?**
    *   Тема:  Роль сім'ї в економіці.  Розвиток економічних знань у сім'ї.
    *   Творчі завдання:  Створення "економічного плану" для сім'ї (визначення потреб, виділення бюджету).
    *   Ресурси:  Інтерактивні ігри про сім'ю, приклади з реального життя.
*   **Місяць 5:  Економіка та підприємництво –  Що таке підприємництво?**
    *   Тема:  Що таке підприємництво?  Як виникають підприємства?
    *   Творчі завдання:  Створення "економічного бізнесу" (визначення потреб, виділення бюджету).
    *   Ресурси:  Відео про підприємництво, приклади з реального життя.
*   **Місяць 6:  Економіка та споживання –  Як ми витрачаємо гроші?**
    *   Тема:  Економічні потреби та бажання.  Як ми вибираємо, що купувати.
    *   Творчі завдання:  Створення "економічного списку покупок" (визначення потреб, порівняння цін).
    *   Ресурси:  Інтерактивні ігри про споживання, приклади з реального життя.
*   **Місяць 7:  Економіка та фінанси –  Що таке банківські рахунки?**
    *   Тема:  Як працюють банківські рахунки?  Як вибирати банк?
    *   Творчі завдання:  Створення "економічного плану" для банківського рахунку (визначення потреб, виділення бюджету).
    *   Ресурси:  Відео про банківські рахунки, приклади з реального життя.
*   **Місяць 8:  Економіка та інвестиції –  Що таке інвестиції?**
    *   Тема:  Що таке інвестиції?  Як інвестувати гроші?
    *   Творчі завдання:  Створення "економічного плану" для інвестицій (визначення потреб, виділення бюджету).
    *   Ресурси:  Відео про інвестиції, приклади з реального життя.
*   **Місяць 9:  Економіка та майбутнє –  Чому економіка важлива?**
    *   Тема:  Вплив економіки на суспільство.  Чому економіка важлива для майбутнього.
    *   Творчі завдання:  Створення "економічного плану" на майбутнє (визначення потреб, виділення бюджету).
    *   Ресурси:  Інтерактивні ігри про майбутнє, приклади з реального життя.

**4.  Додаткові ресурси:**

*   **Інтерактивні ігри:**  Існує багато онлайн-ігор про економіку для дітей (наприклад, "Money Maze", "Economics Games").
*   **Відео:**  YouTube-канали з економічними уроками для дітей (наприклад, "Math Eggs", "Khan Academy Kids").
*   **Книги:**  Книги про економіку для дітей (з адаптованим шрифтом та зрозумілим змістом).
*   **Онлайн-платформи:**  Інтерактивні платформи для навчання економіці (наприклад,  "BrainPop").

**Важливо:**  План курсу може бути адаптований до конкретних потреб та можливостей навчального закладу.  Необхідно враховувати вік учнів, їх рівень знань та інтереси.


### ЦІЛЬОВА АУДИТОРІЯ
{target_auditory}

### ТЕМА
{field_of_study}
""")

while True:
    target = input('Введіть цільову аудиторію курсу: ').strip().lower()

    if not target:
        break

    topic = input('Введіть тему курсу: ').strip().lower()

    if not topic:
        break

    chain = prompt | llm

    response = chain.invoke({
        'target_auditory': target,
        'field_of_study': topic
    })

    print(response + '\n')